#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const PACKAGE_DIR = path.join(ROOT, 'vendor', '@alphaci', 'capability-catalog');
const OUTPUT = path.join(ROOT, 'docs', 'capabilities', 'surface-registry.ts');
const HEADER = [
  '// Generated from @alphaci/capability-catalog catalog.json.',
  '// Surface ownership and package integrity live in the versioned backend package.',
  '// Verify vendor/@alphaci/capability-catalog/provenance.json with scripts/check-capability-package.cjs.',
  '// Do not edit this file by hand; run scripts/generate-capability-surface-registry.cjs.',
].join('\n');

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function render() {
  const metadata = readJson(path.join(PACKAGE_DIR, 'package.json'));
  const catalog = readJson(path.join(PACKAGE_DIR, 'catalog.json'));
  readJson(path.join(PACKAGE_DIR, 'provenance.json'));
  const surfaces = catalog.map((record) => {
    if (!record.surface) {
      throw new Error('catalog record ' + record.key + ' is missing surface data');
    }
    return { key: record.key, ...record.surface };
  });
  return [
    HEADER,
    '',
    '// Package version: ' + metadata.version,
    'export const CAPABILITY_SURFACES = ' + JSON.stringify(surfaces, null, 2) + ' as const;',
    '',
  ].join('\n');
}

function main() {
  const expected = render();
  if (process.argv.includes('--check')) {
    const actual = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (actual !== expected) {
      console.error('Generated output is stale: docs/capabilities/surface-registry.ts');
      process.exitCode = 1;
      return;
    }
    console.log('Checked docs/capabilities/surface-registry.ts from the vendored capability package.');
    return;
  }
  fs.writeFileSync(OUTPUT, expected, 'utf8');
  const metadata = readJson(path.join(PACKAGE_DIR, 'package.json'));
  console.log('Generated docs/capabilities/surface-registry.ts from @alphaci/capability-catalog@' + metadata.version + '.');
}

if (require.main === module) main();

module.exports = { OUTPUT, render };
