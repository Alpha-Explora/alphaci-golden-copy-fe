import fs from "fs";
import path from "path";

describe("workflow current tab migration", () => {
  const componentPath = path.join(process.cwd(), "src/components/product/workflow-current-tab.tsx");
  const overviewHookPath = path.join(process.cwd(), "src/components/product/use-workflow-project-overview.ts");
  const settingsHookPath = path.join(process.cwd(), "src/components/product/use-workflow-settings-preview.ts");
  const telemetryHookPath = path.join(process.cwd(), "src/components/product/use-workflow-project-telemetry.ts");
  const targetListPath = path.join(process.cwd(), "src/components/product/workflow-deployment-targets-list.tsx");
  const targetManagementHookPath = path.join(process.cwd(), "src/components/product/use-workflow-deployment-targets.ts");
  const panelComponentsPath = path.join(process.cwd(), "src/components/product/workflow-current-panels.tsx");
  const resultBannerPath = path.join(process.cwd(), "src/components/product/workflow-current-result-banner.tsx");
  const navigationPath = path.join(process.cwd(), "src/components/product/workflow-current-navigation.tsx");
  const historyPanelPath = path.join(process.cwd(), "src/components/product/workflow-history-panel.tsx");
  const projectsPanelPath = path.join(process.cwd(), "src/components/product/workflow-projects-panel.tsx");
  const projectDetailShellPath = path.join(process.cwd(), "src/components/product/workflow-project-detail-shell.tsx");

  it("keeps project overview state owned by a dedicated hook", () => {
    const componentSource = fs.readFileSync(componentPath, "utf8");

    expect(fs.existsSync(overviewHookPath)).toBe(true);
    expect(componentSource).toContain("useWorkflowProjectOverview");
    expect(componentSource).not.toContain("getProjectOverview(");
    expect(componentSource).not.toContain("syncProjectSnapshot(");
    expect(fs.existsSync(settingsHookPath)).toBe(true);
    expect(componentSource).toContain("useWorkflowSettingsPreview");
    expect(componentSource).not.toContain("getWorkflowSettings(");
    expect(componentSource).not.toContain("previewWorkflowSettings(");
    expect(componentSource).not.toContain("createWorkflowUpdatePullRequest(");
    expect(fs.existsSync(telemetryHookPath)).toBe(true);
    expect(componentSource).toContain("useWorkflowProjectTelemetry");
    expect(componentSource).not.toContain("getProjectCiRuns(");
    expect(componentSource).not.toContain("getProjectDeployments(");
    expect(componentSource).not.toContain("getProjectAuditEvents(");
    expect(componentSource).not.toContain("getProjectDrift(");
    expect(componentSource).not.toContain("runProjectDriftDetection(");
    expect(componentSource).not.toContain("repairProjectDriftFinding(");
    expect(fs.existsSync(targetListPath)).toBe(true);
    expect(componentSource).toContain("DeploymentTargetsList");
    expect(fs.existsSync(targetManagementHookPath)).toBe(true);
    expect(fs.readFileSync(targetListPath, "utf8")).toContain("useWorkflowDeploymentTargets");
    expect(fs.existsSync(panelComponentsPath)).toBe(true);
    expect(componentSource).toContain("workflow-current-panels");
    expect(componentSource).not.toContain("function WorkflowStageList");
    expect(componentSource).not.toContain("function EnvMetadataList");
    expect(componentSource).not.toContain("function CiRunsList");
    expect(componentSource).not.toContain("function DeploymentHistoryList");
    expect(componentSource).not.toContain("function DriftFindingsPanel");
    expect(fs.existsSync(resultBannerPath)).toBe(true);
    expect(componentSource).toContain("WorkflowLatestResultBanner");
    expect(componentSource).not.toContain("latest-result-banner glass-panel");
    expect(fs.existsSync(navigationPath)).toBe(true);
    expect(componentSource).toContain("WorkflowCurrentSubtabBar");
    expect(componentSource).not.toContain("current-subtab-bar");
    expect(fs.existsSync(historyPanelPath)).toBe(true);
    expect(componentSource).toContain("WorkflowHistoryPanel");
    expect(componentSource).not.toContain("Preview YAML config");
    expect(componentSource).not.toContain("Generate your first workflow");
    expect(fs.existsSync(projectsPanelPath)).toBe(true);
    expect(componentSource).toContain("WorkflowProjectsLoadingState");
    expect(componentSource).toContain("WorkflowProjectsEmptyState");
    expect(componentSource).toContain("WorkflowProjectList");
    expect(componentSource).not.toContain("No provisioned projects yet.");
    expect(componentSource).not.toContain('className="project-list"');
    expect(fs.existsSync(projectDetailShellPath)).toBe(true);
    expect(componentSource).toContain("WorkflowProjectDetailHeader");
    expect(componentSource).toContain("WorkflowProjectDetailActions");
    expect(componentSource).toContain("WorkflowProjectDetailTabs");
    expect(componentSource).not.toContain('className="project-detail-header"');
    expect(componentSource).not.toContain('className="project-detail-actions"');
    expect(componentSource).not.toContain('className="project-inner-tabs"');
    expect(componentSource).not.toContain("updateDeploymentTarget(");
    expect(componentSource).not.toContain("syncDeploymentTarget(");
    expect(componentSource).not.toContain("detachDeploymentTarget(");
  });

  it("keeps the first workflow-current extraction inside migration budgets", () => {
    const componentSource = fs.readFileSync(componentPath, "utf8");
    const hookSource = fs.existsSync(overviewHookPath) ? fs.readFileSync(overviewHookPath, "utf8") : "";
    const settingsHookSource = fs.existsSync(settingsHookPath) ? fs.readFileSync(settingsHookPath, "utf8") : "";
    const telemetryHookSource = fs.existsSync(telemetryHookPath) ? fs.readFileSync(telemetryHookPath, "utf8") : "";
    const targetListSource = fs.existsSync(targetListPath) ? fs.readFileSync(targetListPath, "utf8") : "";
    const targetManagementHookSource = fs.existsSync(targetManagementHookPath) ? fs.readFileSync(targetManagementHookPath, "utf8") : "";
    const panelComponentsSource = fs.existsSync(panelComponentsPath) ? fs.readFileSync(panelComponentsPath, "utf8") : "";
    const resultBannerSource = fs.existsSync(resultBannerPath) ? fs.readFileSync(resultBannerPath, "utf8") : "";
    const navigationSource = fs.existsSync(navigationPath) ? fs.readFileSync(navigationPath, "utf8") : "";
    const historyPanelSource = fs.existsSync(historyPanelPath) ? fs.readFileSync(historyPanelPath, "utf8") : "";
    const projectsPanelSource = fs.existsSync(projectsPanelPath) ? fs.readFileSync(projectsPanelPath, "utf8") : "";
    const projectDetailShellSource = fs.existsSync(projectDetailShellPath) ? fs.readFileSync(projectDetailShellPath, "utf8") : "";
    const mojibakePattern = /[\u00c2\u00e2]/;

    expect(componentSource.trim().split(/\r?\n/).length).toBeLessThanOrEqual(705);
    expect(hookSource.trim().split(/\r?\n/).length).toBeLessThanOrEqual(350);
    expect(settingsHookSource.trim().split(/\r?\n/).length).toBeLessThanOrEqual(350);
    expect(telemetryHookSource.trim().split(/\r?\n/).length).toBeLessThanOrEqual(350);
    expect(targetListSource.trim().split(/\r?\n/).length).toBeLessThanOrEqual(260);
    expect(targetManagementHookSource.trim().split(/\r?\n/).length).toBeLessThanOrEqual(250);
    expect(panelComponentsSource.trim().split(/\r?\n/).length).toBeLessThanOrEqual(320);
    expect(resultBannerSource.trim().split(/\r?\n/).length).toBeLessThanOrEqual(130);
    expect(navigationSource.trim().split(/\r?\n/).length).toBeLessThanOrEqual(90);
    expect(historyPanelSource.trim().split(/\r?\n/).length).toBeLessThanOrEqual(280);
    expect(projectsPanelSource.trim().split(/\r?\n/).length).toBeLessThanOrEqual(220);
    expect(projectDetailShellSource.trim().split(/\r?\n/).length).toBeLessThanOrEqual(220);
    expect(hookSource).not.toMatch(mojibakePattern);
    expect(settingsHookSource).not.toMatch(mojibakePattern);
    expect(telemetryHookSource).not.toMatch(mojibakePattern);
    expect(targetListSource).not.toMatch(mojibakePattern);
    expect(targetManagementHookSource).not.toMatch(mojibakePattern);
    expect(panelComponentsSource).not.toMatch(mojibakePattern);
    expect(resultBannerSource).not.toMatch(mojibakePattern);
    expect(navigationSource).not.toMatch(mojibakePattern);
    expect(historyPanelSource).not.toMatch(mojibakePattern);
    expect(projectsPanelSource).not.toMatch(mojibakePattern);
    expect(projectDetailShellSource).not.toMatch(mojibakePattern);
  });
});
